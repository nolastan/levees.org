#!/usr/bin/env python3
"""One-time import of levees.org content from the WordPress REST API dump.

Usage: python3 scripts/import_wordpress.py <dump-dir>

<dump-dir> holds posts.json, pages.json, comments.json, categories.json,
tags.json and users.json, as saved from https://levees.org/wp-json/wp/v2/.
Writes _posts/, pages/, _data/comments/, _data/categories.yml, _data/tags.yml,
shortlinks.json. Kept in the repo as a record of how the content was
converted; it is not part of the build.
"""
import html, json, os, re, sys, urllib.parse
from datetime import datetime, timezone

DUMP = sys.argv[1]
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def load(name):
    return json.load(open(os.path.join(DUMP, name + '.json')))

posts, pages, comments = load('posts'), load('pages'), load('comments')
cats, tags, users = load('categories'), load('tags'), load('users')
user_names = {u['id']: u['name'] for u in users}
user_slugs = {u['id']: u['slug'] for u in users}
post_authors = {x['id']: x['author'] for x in posts + pages}
cat_slug = {c['id']: c['slug'] for c in cats}
tag_slug = {t['id']: t['slug'] for t in tags}

SITE = re.compile(r'https?://(?:www\.)?levees\.org(?=/|"|\'|\s|$)')
ATTR = re.compile(r'''(\b(?:href|src|srcset|action|data-[\w-]+|value|poster)\s*=\s*)("[^"]*"|'[^']*')''', re.I)

def relativize(content):
    """Make links to levees.org root-relative, inside attribute values only.
    Visible text (e.g. a URL written out in a paragraph) is left untouched."""
    def fix(m):
        v = SITE.sub('', m.group(2))
        v = re.sub(r'^(["\'])(?=\1)', r'\1/', v) if v in ('""', "''") else v
        return m.group(1) + v
    return ATTR.sub(fix, content)

def frontend_html(content):
    """The REST API renders content slightly differently from the theme:
    caption shortcodes come back wrapped in <p>, and their ids get a "-2"
    suffix (the API renders captions twice, for the excerpt and the body).
    Undo both so the pages match what visitors saw."""
    content = re.sub(r'<p>(<div id="attachment_[^"]*"[^>]*>(?:(?!</div>).)*</div>)</p>', r'\1', content, flags=re.S)
    content = re.sub(r'<p>(<div id="attachment_[^"]*"[^>]*>(?:(?!</div>).)*</div>)', r'\1<p>', content, flags=re.S)
    content = re.sub(r'((?:id|aria-describedby)="(?:caption-)?attachment[-_]\d+)-\d+"', r'\1"', content)
    return content

def yq(s):
    """YAML double-quoted scalar."""
    return json.dumps(s, ensure_ascii=False)

def path_of(link):
    return urllib.parse.unquote(link.replace('https://levees.org', '').replace('http://levees.org', '')) or '/'

def ts(local, gmt):
    """WordPress local time + offset derived from the GMT field."""
    l = datetime.fromisoformat(local); g = datetime.fromisoformat(gmt)
    off = int((l - g).total_seconds() // 60)
    sign = '-' if off < 0 else '+'
    off = abs(off)
    return f"{local.replace('T', ' ')} {sign}{off // 60:02d}{off % 60:02d}"

def aioseo_description(item):
    j = item.get('aioseo_head_json') or {}
    return j.get('description') or ''

def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write(text)

shortlinks = {}

# ---- posts
for p in posts:
    perm = path_of(p['link'])
    slug = urllib.parse.unquote(p['slug'])
    fname = f"{p['date'][:10]}-{slug}.html"
    fm = [
        '---',
        f"title: {yq(p['title']['rendered'])}",
        f"date: {ts(p['date'], p['date_gmt'])}",
        f"last_modified_at: {ts(p['modified'], p['modified_gmt'])}",
        f"author: {yq(user_names.get(p['author'], ''))}",
        f"permalink: {yq(perm)}",
        f"wp_id: {p['id']}",
        'categories: [' + ', '.join(yq(cat_slug[c]) for c in p['categories']) + ']',
        'tags: [' + ', '.join(yq(tag_slug[t]) for t in p['tags'] if t in tag_slug) + ']',
    ]
    d = aioseo_description(p)
    if d: fm.append(f"description: {yq(html.unescape(d))}")
    fm.append(f"excerpt: {yq(relativize(p['excerpt']['rendered']))}")
    fm.append('---')
    write(os.path.join(ROOT, '_posts', fname), '\n'.join(fm) + '\n' + relativize(frontend_html(p['content']['rendered'])))
    shortlinks[str(p['id'])] = perm

# ---- pages
page_by_id = {g['id']: g for g in pages}
for g in pages:
    perm = path_of(g['link'])
    if perm == '/' or g['template'] == 'blog.php':
        continue  # home page is index.html; /blog/ is generated by _plugins/wordpress.rb
    rel = perm.strip('/') + '.html'
    fm = [
        '---',
        f"title: {yq(g['title']['rendered'])}",
        f"date: {ts(g['date'], g['date_gmt'])}",
        f"last_modified_at: {ts(g['modified'], g['modified_gmt'])}",
        f"permalink: {yq(perm)}",
        f"wp_id: {g['id']}",
    ]
    if g['parent']: fm.append(f"wp_parent: {g['parent']}")
    if g['template']: fm.append(f"wp_template: {yq(g['template'])}")
    if g['menu_order']: fm.append(f"menu_order: {g['menu_order']}")
    if any(x['parent'] == g['id'] for x in pages): fm.append('wp_has_children: true')
    d = aioseo_description(g)
    if d: fm.append(f"description: {yq(html.unescape(d))}")
    fm.append('---')
    body = relativize(frontend_html(g['content']['rendered']))
    write(os.path.join(ROOT, 'pages', rel), '\n'.join(fm) + '\n' + body)
    shortlinks[str(g['id'])] = perm

# ---- comments, one file per post, oldest first (WordPress default order)
by_post = {}
for c in sorted(comments, key=lambda c: (c['date_gmt'], c['id'])):
    by_post.setdefault(c['post'], []).append(c)
for pid, cs in by_post.items():
    out = []
    for c in cs:
        av = c['author_avatar_urls'].get('96', '')
        h = re.search(r'/avatar/([0-9a-f]+)', av)
        out += [
            f"- id: {c['id']}",
            f"  parent: {c['parent']}",
            f"  author: {yq(html.unescape(c['author_name']))}",
            f"  author_url: {yq('' if c['author_url'] in ('http://', 'https://') else c['author_url'])}",
            f"  avatar: {yq(h.group(1) if h else '')}",
        ]
        if c['author']:
            # WordPress marks comments by registered users (and by the post's author).
            cls = f"byuser comment-author-{user_slugs.get(c['author'], '')}"
            if post_authors.get(pid) == c['author']: cls += ' bypostauthor'
            out.append(f"  user_class: {yq(cls)}")
        out += [
            f"  date: {yq(c['date'])}",
            f"  content: {yq(relativize(c['content']['rendered']))}",
        ]
    write(os.path.join(ROOT, '_data', 'comments', f'{pid}.yml'), '\n'.join(out) + '\n')

# ---- taxonomies
def tax(items, fname):
    out = []
    for t in sorted(items, key=lambda t: t['slug']):
        out += [f"{urllib.parse.unquote(t['slug'])}:", f"  id: {t['id']}", f"  name: {yq(html.unescape(t['name']))}"]
        if t.get('description'): out.append(f"  description: {yq(t['description'])}")
    write(os.path.join(ROOT, '_data', fname), '\n'.join(out) + '\n')
tax(cats, 'categories.yml')
tax(tags, 'tags.yml')

write(os.path.join(ROOT, 'shortlinks.json'), json.dumps(shortlinks, indent=0, ensure_ascii=False))
print(len(posts), 'posts;', len(pages), 'pages;', len(comments), 'comments')
